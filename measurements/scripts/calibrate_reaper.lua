-- Stage 3 only. Run in a dedicated instance with an empty project.
local _, script = reaper.get_action_context()
local root = script:match('^(.*)[/\\]measurements[/\\]scripts[/\\]')
assert(root, 'Cannot locate project root')
assert(reaper.CountTracks(0) == 0, 'Requires empty dedicated project')
local log = assert(io.open(root..'/measurements/results/reaper_calibration_setup.txt','w'))
log:write('REAPER '..reaper.GetAppVersion()..'\n')
for id=40000,43000 do
 local name=reaper.kbd_getTextFromCmd(id,0)
 if name and name:lower():find('render') then log:write(id..' '..name..'\n') end
end
reaper.GetSetProjectInfo(0,'PROJECT_SRATE',44100,true)
reaper.GetSetProjectInfo(0,'PROJECT_SRATE_USE',1,true)
reaper.InsertTrackAtIndex(0,false)
local track=reaper.GetTrack(0,0)
reaper.SetOnlyTrackSelected(track)
reaper.InsertMedia(root..'/measurements/signals/calibration-impulse-44100.wav',0)
local fx=reaper.TrackFX_AddByName(track,'ReaEQ (Cockos)',false,-1)
assert(fx>=0,'ReaEQ missing')
-- Keep only the first existing bell. Disable default shelves and second bell.
assert(reaper.TrackFX_SetEQBandEnabled(track,fx,1,0,false))
assert(reaper.TrackFX_SetEQBandEnabled(track,fx,4,0,false))
assert(reaper.TrackFX_SetEQBandEnabled(track,fx,2,1,false))
assert(reaper.TrackFX_SetEQParam(track,fx,2,0,0,100,false))
assert(reaper.TrackFX_SetEQParam(track,fx,2,0,1,6,false))
assert(reaper.TrackFX_SetEQParam(track,fx,2,0,2,2,false))
for i=0,reaper.TrackFX_GetNumParams(track,fx)-1 do
 local _,name=reaper.TrackFX_GetParamName(track,fx,i,'')
 local _,text=reaper.TrackFX_GetFormattedParamValue(track,fx,i,'')
 log:write(i..' '..name..' = '..text..'\n')
end
reaper.GetSetProjectInfo(0,'RENDER_SRATE',44100,true)
reaper.GetSetProjectInfo(0,'RENDER_CHANNELS',2,true)
reaper.GetSetProjectInfo(0,'RENDER_SETTINGS',0,true)
reaper.GetSetProjectInfo(0,'RENDER_BOUNDSFLAG',0,true)
reaper.GetSetProjectInfo(0,'RENDER_STARTPOS',0,true)
reaper.GetSetProjectInfo(0,'RENDER_ENDPOS',6,true)
reaper.GetSetProjectInfo(0,'RENDER_DITHER',0,true)
reaper.GetSetProjectInfo(0,'RENDER_TAILFLAG',0,true)
reaper.GetSetProjectInfo_String(0,'RENDER_FILE',root..'/measurements/renders/calibration',true)
reaper.GetSetProjectInfo_String(0,'RENDER_PATTERN','reaeq-impulse',true)
local _,fmt=reaper.GetSetProjectInfo_String(0,'RENDER_FORMAT','',false)
log:write('RENDER_FORMAT='..fmt..'\n')
log:close()
reaper.Main_SaveProjectEx(0,root..'/eq_reaper_project/stage3-calibration.rpp',0)
